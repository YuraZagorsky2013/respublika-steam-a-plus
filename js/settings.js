function applyLanguage(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.uk;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      if (el.tagName === "INPUT" && el.hasAttribute("placeholder")) {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  localStorage.setItem("aplus_lang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const btnSettingsOpen = document.getElementById("btn-settings-open");
  const btnSettingsClose = document.getElementById("btn-settings-close");
  const modalSettings = document.getElementById("modal-settings");

  const toggleDarkMode = document.getElementById("toggle-dark-mode");
  const toggleLiquidGlass = document.getElementById("toggle-liquid-glass");
  const toggleSmoothActions = document.getElementById("toggle-smooth-actions");
  const selectLanguage = document.getElementById("select-language");

  // Мова за замовчуванням — Українська (uk)
  const currentLang = localStorage.getItem("aplus_lang") || "uk";
  if (selectLanguage) {
    selectLanguage.value = currentLang;
  }
  applyLanguage(currentLang);

  // Відкриття налаштувань та перевірка прав Адміністратора
  if (btnSettingsOpen) {
    btnSettingsOpen.addEventListener("click", () => {
      const adminBox = document.getElementById("admin-settings-section");
      if (adminBox) {
        if (window.isUserAdmin && isUserAdmin()) {
          adminBox.classList.remove("hidden");
        } else {
          adminBox.classList.add("hidden");
        }
      }
      if (modalSettings) modalSettings.classList.remove("hidden");
    });
  }

  if (btnSettingsClose) {
    btnSettingsClose.addEventListener("click", () => {
      if (modalSettings) modalSettings.classList.add("hidden");
    });
  }

  if (selectLanguage) {
    selectLanguage.addEventListener("change", (e) => {
      applyLanguage(e.target.value);
    });
  }

  if (toggleDarkMode) {
    toggleDarkMode.addEventListener("change", (e) => {
      if (e.target.checked) {
        document.body.classList.add("dark-mode");
        document.body.classList.remove("light-mode");
      } else {
        document.body.classList.add("light-mode");
        document.body.classList.remove("dark-mode");
      }
    });
  }

  if (toggleLiquidGlass) {
    toggleLiquidGlass.addEventListener("change", (e) => {
      if (e.target.checked) {
        document.body.classList.add("liquid-glass-active");
      } else {
        document.body.classList.remove("liquid-glass-active");
      }
    });
  }

  if (toggleSmoothActions) {
    toggleSmoothActions.addEventListener("change", (e) => {
      if (e.target.checked) {
        document.body.classList.add("smooth-actions");
      } else {
        document.body.classList.remove("smooth-actions");
      }
    });
  }

  // Обробники для Адмін-панелі
  const formNews = document.getElementById("form-admin-news");
  if (formNews) {
    formNews.addEventListener("submit", async (e) => {
      e.preventDefault();
      const titleInput = document.getElementById("admin-news-title");
      const descInput = document.getElementById("admin-news-desc");
      const hotInput = document.getElementById("admin-news-hot");

      if (titleInput && descInput && window.addSupabaseNews) {
        const createdNews = await addSupabaseNews(titleInput.value, descInput.value, hotInput ? hotInput.checked : false);
        if (!createdNews) {
          alert("Не вдалося опублікувати новину.");
          return;
        }
        alert("Новину опубліковано!");
        titleInput.value = "";
        descInput.value = "";
        if (hotInput) hotInput.checked = false;
        if (window.loadHomeNews) loadHomeNews();
      }
    });
  }

  const formLesson = document.getElementById("form-admin-lesson");
  if (formLesson) {
    formLesson.addEventListener("submit", async (e) => {
      e.preventDefault();
      const dayInput = document.getElementById("admin-lesson-day");
      const numInput = document.getElementById("admin-lesson-num");
      const subjectInput = document.getElementById("admin-lesson-subject");
      const roomInput = document.getElementById("admin-lesson-room");
      const timeInput = document.getElementById("admin-lesson-time");

      if (dayInput && numInput && subjectInput && roomInput && timeInput && window.addSupabaseLesson) {
        const createdLesson = await addSupabaseLesson(
          dayInput.value,
          parseInt(numInput.value),
          subjectInput.value,
          roomInput.value,
          timeInput.value
        );
        if (!createdLesson) {
          alert("Не вдалося додати урок.");
          return;
        }
        alert("Урок додано до розкладу!");
        numInput.value = "";
        subjectInput.value = "";
        roomInput.value = "";
        timeInput.value = "";
        if (window.loadSchedule) loadSchedule();
      }
    });
  }

  const btnCloseSite = document.getElementById("btn-admin-close-site");
  if (btnCloseSite) {
    btnCloseSite.addEventListener("click", () => {
      if (confirm("Зачинити сайт на 5 хвилин для всіх користувачів?")) {
        const lockUntil = Date.now() + 5 * 60 * 1000;
        localStorage.setItem("aplus_site_lock", lockUntil);
        if (window.checkSiteLock) checkSiteLock();
      }
    });
  }
});